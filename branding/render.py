# ---- SVG ---------------------------------------------------------------------

def fmt(v: float) -> str:
    text = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def path_d(path: list[tuple]) -> str:
    return " ".join(cmd[0] + (" " + " ".join(fmt(v) for v in cmd[1:]) if len(cmd) > 1 else "") for cmd in path)


def svg(shapes: list[dict], width: int, height: int, title: str, symbolic: bool = False) -> str:
    """Shapes with a 'knock' erase a band around themselves from what lies below (an SVG mask)."""
    defs, body = [], []
    for i, shape in enumerate(shapes):
        d = path_d(shape["path"])
        if shape.get("knock") and body:
            mid = f"knock{i}"
            if "stroke" in shape:
                cut = (f'<path d="{d}" fill="none" stroke="#000" stroke-width="{fmt(shape["width"] + 2 * shape["knock"])}" '
                       'stroke-linecap="round" stroke-linejoin="round"/>')
            else:
                cut = (f'<path d="{d}" fill="#000" fill-rule="{shape.get("rule", "nonzero")}" stroke="#000" '
                       f'stroke-width="{fmt(2 * shape["knock"])}" stroke-linejoin="round"/>')
            defs.append(f'<mask id="{mid}" maskUnits="userSpaceOnUse" x="0" y="0" width="{width}" height="{height}">'
                        f'<rect width="{width}" height="{height}" fill="#fff"/>{cut}</mask>')
            body = [f'<g mask="url(#{mid})">'] + body + ["</g>"]
        if symbolic:
            paint = 'class="ColorScheme-Text" style="fill:currentColor"' if "stroke" not in shape else \
                'class="ColorScheme-Text" style="fill:none;stroke:currentColor"'
        else:
            paint = f'fill="{shape["fill"]}"' if "stroke" not in shape else f'fill="none" stroke="{shape["stroke"]}"'
        if "stroke" in shape:
            body.append(f'<path d="{d}" {paint} stroke-width="{fmt(shape["width"])}" stroke-linecap="round" '
                        'stroke-linejoin="round"/>')
        else:
            body.append(f'<path d="{d}" {paint} fill-rule="{shape.get("rule", "nonzero")}"/>')
    style = ('<style type="text/css" id="current-color-scheme">.ColorScheme-Text { color:#232629; }</style>'
             if symbolic else "")
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- {SPDX} -->\n<!-- {NOTE} -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">\n'
            f'<title>{title}</title>\n{style}' + ("<defs>" + "".join(defs) + "</defs>\n" if defs else "")
            + "\n".join(body) + "\n</svg>\n")


# ---- raster ------------------------------------------------------------------

def flatten(path: list[tuple], scale: float) -> list[list[tuple[float, float]]]:
    polys, cur, start, pos = [], [], (0.0, 0.0), (0.0, 0.0)
    for cmd in path:
        if cmd[0] == "M":
            if len(cur) > 1:
                polys.append(cur)
            pos = start = (cmd[1] * scale, cmd[2] * scale)
            cur = [pos]
        elif cmd[0] == "L":
            pos = (cmd[1] * scale, cmd[2] * scale)
            cur.append(pos)
        elif cmd[0] == "C":
            p0 = pos
            p1, p2, p3 = ((cmd[1] * scale, cmd[2] * scale), (cmd[3] * scale, cmd[4] * scale),
                          (cmd[5] * scale, cmd[6] * scale))
            length = math.dist(p0, p1) + math.dist(p1, p2) + math.dist(p2, p3)
            n = max(4, min(96, int(length / 2)))
            for i in range(1, n + 1):
                t = i / n
                u = 1 - t
                cur.append((u * u * u * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t * t * t * p3[0],
                            u * u * u * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t * t * t * p3[1]))
            pos = p3
        elif cmd[0] == "Z":
            if len(cur) > 1:
                polys.append(cur)
            cur = [start]
            pos = start
    if len(cur) > 1:
        polys.append(cur)
    return polys


def area(poly: list[tuple[float, float]]) -> float:
    return sum(poly[i - 1][0] * poly[i][1] - poly[i][0] * poly[i - 1][1] for i in range(len(poly))) / 2


def positive(poly):
    return poly if area(poly) >= 0 else poly[::-1]


def disc(cx: float, cy: float, r: float, n: int = 32):
    return [(cx + r * math.cos(2 * math.pi * i / n), cy + r * math.sin(2 * math.pi * i / n)) for i in range(n)]


def stroke_polys(polys, width: float):
    """A round-capped, round-joined stroke as a union of quads and discs (all wound alike)."""
    out, r = [], width / 2
    for poly in polys:
        pts = poly + [poly[0]] if poly[0] != poly[-1] else poly
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            dx, dy = x1 - x0, y1 - y0
            n = math.hypot(dx, dy)
            if n == 0:
                continue
            nx, ny = -dy / n * r, dx / n * r
            out.append(positive([(x0 + nx, y0 + ny), (x1 + nx, y1 + ny), (x1 - nx, y1 - ny), (x0 - nx, y0 - ny)]))
            out.append(disc(x1, y1, r, max(12, int(r * 2))))
    return out


SUB = 8  # vertical samples per pixel; horizontal coverage is exact


def coverage(polys, w: int, h: int, rule: str) -> dict[int, list[float]]:
    """Coverage of each pixel row (only rows touched), 0..1."""
    edges = []
    for poly in polys:
        for i in range(len(poly)):
            (x0, y0), (x1, y1) = poly[i - 1], poly[i]
            if y0 != y1:
                edges.append((x0, y0, x1, y1))
    if not edges:
        return {}
    ymin = max(0, int(min(min(e[1], e[3]) for e in edges)))
    ymax = min(h - 1, int(max(max(e[1], e[3]) for e in edges)) + 1)
    rows: dict[int, list[float]] = {}
    for py in range(ymin, ymax + 1):
        row = None
        for s in range(SUB):
            y = py + (s + 0.5) / SUB
            xs = []
            for x0, y0, x1, y1 in edges:
                if (y0 <= y < y1) or (y1 <= y < y0):
                    xs.append((x0 + (y - y0) * (x1 - x0) / (y1 - y0), 1 if y1 > y0 else -1))
            if not xs:
                continue
            xs.sort()
            wind, spans = 0, []
            for i, (x, d) in enumerate(xs):
                inside = (wind % 2 == 1) if rule == "evenodd" else wind != 0
                wind = wind + 1 if rule == "evenodd" else wind + d
                now = (wind % 2 == 1) if rule == "evenodd" else wind != 0
                if not inside and now:
                    start = x
                elif inside and not now:
                    spans.append((start, x))
            if not spans:
                continue
            if row is None:
                row = [0.0] * w
            for a, b in spans:
                a, b = max(a, 0.0), min(b, float(w))
                if b <= a:
                    continue
                ia, ib = int(a), int(b)
                if ia == ib:
                    row[ia] += (b - a) / SUB
                    continue
                row[ia] += (ia + 1 - a) / SUB
                for x in range(ia + 1, min(ib, w)):
                    row[x] += 1 / SUB
                if ib < w:
                    row[ib] += (b - ib) / SUB
        if row is not None:
            rows[py] = row
    return rows


class Canvas:
    def __init__(self, w: int, h: int, background: str | None = None):
        self.w, self.h = w, h
        r, g, b = hexrgb(background) if background else (0, 0, 0)
        a = 1.0 if background else 0.0
        self.px = [[r, g, b, a] * w for _ in range(h)]

    def paint(self, rows, colour: str, opacity: float = 1.0):
        cr, cg, cb = hexrgb(colour)
        for y, row in rows.items():
            line = self.px[y]
            for x, cov in enumerate(row):
                if cov <= 0:
                    continue
                a = min(cov, 1.0) * opacity
                i = 4 * x
                da = line[i + 3]
                oa = a + da * (1 - a)
                if oa <= 0:
                    continue
                line[i] = (cr * a + line[i] * da * (1 - a)) / oa
                line[i + 1] = (cg * a + line[i + 1] * da * (1 - a)) / oa
                line[i + 2] = (cb * a + line[i + 2] * da * (1 - a)) / oa
                line[i + 3] = oa

    def erase(self, rows):
        for y, row in rows.items():
            line = self.px[y]
            for x, cov in enumerate(row):
                if cov > 0:
                    line[4 * x + 3] *= 1 - min(cov, 1.0)

    def draw(self, shapes: list[dict], scale: float):
        for shape in shapes:
            polys = flatten(shape["path"], scale)
            if "stroke" in shape:
                body = stroke_polys(polys, shape["width"] * scale)
                rule = "nonzero"
            else:
                body = polys
                rule = shape.get("rule", "nonzero")
            if shape.get("knock"):
                k = shape["knock"] * scale
                if "stroke" in shape:
                    cut = stroke_polys(polys, shape["width"] * scale + 2 * k)
                    self.erase(coverage(cut, self.w, self.h, "nonzero"))
                else:
                    self.erase(coverage(body, self.w, self.h, rule))
                    self.erase(coverage(stroke_polys(polys, 2 * k), self.w, self.h, "nonzero"))
            self.paint(coverage(body, self.w, self.h, rule), shape.get("stroke") or shape["fill"],
                       shape.get("opacity", 1.0))

    def png(self, alpha: bool = True) -> bytes:
        bayer = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
        raw = bytearray()
        for y, line in enumerate(self.px):
            raw.append(0)
            for x in range(self.w):
                r, g, b, a = line[4 * x:4 * x + 4]
                dither = (bayer[y % 4][x % 4] + 0.5) / 16 - 0.5 if not alpha else 0.0
                vals = (r, g, b, a) if alpha else (r * a, g * a, b * a)
                raw.extend(max(0, min(255, int(v * 255 + 0.5 + dither))) for v in vals)
        def chunk(kind: bytes, body: bytes) -> bytes:
            return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)
        ihdr = struct.pack(">IIBBBBB", self.w, self.h, 8, 6 if alpha else 2, 0, 0, 0)
        return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
                + chunk(b"IEND", b""))


def raster(shapes: list[dict], box: int | tuple[int, int], size: int | tuple[int, int],
           background: str | None = None) -> bytes:
    bw, bh = (box, box) if isinstance(box, int) else box
    w, h = (size, size) if isinstance(size, int) else size
    canvas = Canvas(w, h, background)
    canvas.draw(shapes, w / bw)
    return canvas.png(alpha=background is None)


# ---- the boot splash spinner and the wallpaper --------------------------------------

def spinner_frame(i: int, frames: int, size: int = 48) -> list[dict]:
    """An arc of a quarter turn, rotating; drawn in a 48 x 48 box."""
    start = 2 * math.pi * i / frames
    pts = [(24 + 18 * math.cos(start + t * math.pi / 2 / 24), 24 + 18 * math.sin(start + t * math.pi / 2 / 24))
           for t in range(25)]
    ring = [(24 + 18 * math.cos(2 * math.pi * t / 64), 24 + 18 * math.sin(2 * math.pi * t / 64)) for t in range(64)]
    arc = [("M", *pts[0])] + [("L", *p) for p in pts[1:]]
    track = [("M", *ring[0])] + [("L", *p) for p in ring[1:]] + [("Z",)]
    return [{"path": track, "stroke": "#27324A", "width": 4}, {"path": arc, "stroke": BLUE, "width": 4}]


def wallpaper(w: int, h: int) -> bytes:
    """Near-black ground with a faint blue glow and the lotus, very low in contrast."""
    canvas = Canvas(w, h, SURFACE)
    base, glow = hexrgb(SURFACE), hexrgb("#0E2A4A")
    cx, cy, radius = 0.5 * w, 1.05 * h, 0.95 * max(w, h)
    for y in range(h):
        line = canvas.px[y]
        for x in range(w):
            d = min(1.0, math.hypot(x - cx, (y - cy) * 1.35) / radius)
            k = (1 - d) ** 2.2
            i = 4 * x
            line[i] = base[0] + (glow[0] - base[0]) * k
            line[i + 1] = base[1] + (glow[1] - base[1]) * k
            line[i + 2] = base[2] + (glow[2] - base[2]) * k
    # The mark is drawn on a layer of its own (its gaps are cut into the
    # layer, not into the ground) and laid over the ground, faintly.
    size = 0.42 * h
    layer = Canvas(w, h)
    layer.draw(transform(mark_shapes(), size / 512, (w - size) / 2, 0.46 * h - size / 2), 1.0)
    opacity = 0.16
    for y in range(h):
        top, bottom = layer.px[y], canvas.px[y]
        for i in range(0, 4 * w, 4):
            a = top[i + 3] * opacity
            if a > 0:
                bottom[i] = top[i] * a + bottom[i] * (1 - a)
                bottom[i + 1] = top[i + 1] * a + bottom[i + 1] * (1 - a)
                bottom[i + 2] = top[i + 2] * a + bottom[i + 2] * (1 - a)
    return canvas.png(alpha=False)


