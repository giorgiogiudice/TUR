def hexrgb(colour: str) -> tuple[float, float, float]:
    colour = colour.lstrip("#")
    return tuple(int(colour[i:i + 2], 16) / 255 for i in (0, 2, 4))


# ---- geometry ----------------------------------------------------------------
# A path is a list of commands: ("M", x, y), ("L", x, y), ("C", x1, y1, x2, y2, x, y), ("Z",).

def mirror(path: list[tuple], axis: float = 256.0) -> list[tuple]:
    out = []
    for cmd in path:
        if cmd[0] == "Z":
            out.append(cmd)
            continue
        coords = list(cmd[1:])
        for i in range(0, len(coords), 2):
            coords[i] = 2 * axis - coords[i]
        out.append((cmd[0], *coords))
    return out


def drop(cx: float, top: float, bottom: float, half: float, at: float, shoulder: float) -> list[tuple]:
    """A flame or drop: pointed top, round belly at `at`, pointed bottom."""
    return [
        ("M", cx, top),
        ("C", cx + half * shoulder, top + (at - top) * 0.40, cx + half, at - (at - top) * 0.35, cx + half, at),
        ("C", cx + half, at + (bottom - at) * 0.55, cx + half * 0.45, bottom - (bottom - at) * 0.18, cx, bottom),
        ("C", cx - half * 0.45, bottom - (bottom - at) * 0.18, cx - half, at + (bottom - at) * 0.55, cx - half, at),
        ("C", cx - half, at - (at - top) * 0.35, cx - half * shoulder, top + (at - top) * 0.40, cx, top),
        ("Z",),
    ]


def lemniscate(cx: float, cy: float, a: float, n: int = 96) -> list[tuple]:
    """The infinity sign (lemniscate of Bernoulli), as a closed polyline."""
    pts = []
    for i in range(n):
        t = 2 * math.pi * i / n
        d = 1 + math.sin(t) ** 2
        pts.append((cx + a * math.cos(t) / d, cy + a * math.sin(t) * math.cos(t) / d * 1.25))
    return [("M", *pts[0])] + [("L", *p) for p in pts[1:]] + [("Z",)]


BACK_PETAL = [("M", 230, 338), ("C", 170, 318, 120, 250, 112, 132), ("C", 168, 166, 206, 214, 232, 286), ("Z",)]
FRONT_PETAL = [("M", 256, 384), ("C", 204, 338, 140, 256, 26, 208), ("C", 70, 300, 150, 366, 256, 384), ("Z",)]


def mark_shapes(mono: str | None = None) -> list[dict]:
    """The lotus and flame, in a 512 x 512 box. `mono` draws everything in one colour."""
    def c(colour: str) -> str:
        return mono or colour
    gap = 14  # transparent gap where a shape lies over another: keeps the parts apart at small sizes
    flame = drop(256, 34, 352, 76, 218, 0.30)
    hole = drop(256, 124, 322, 40, 236, 0.30)
    core = drop(256, 196, 300, 21, 262, 0.25)
    return [
        {"path": BACK_PETAL, "fill": c(BLUE_DEEP)},
        {"path": mirror(BACK_PETAL), "fill": c(BLUE_DEEP)},
        {"path": flame + hole, "fill": c(SILVER), "rule": "evenodd", "knock": gap},
        {"path": core, "fill": c(SILVER_LIGHT)},
        {"path": FRONT_PETAL, "fill": c(BLUE), "knock": gap},
        {"path": mirror(FRONT_PETAL), "fill": c(BLUE), "knock": gap},
        {"path": lemniscate(256, 424, 118), "stroke": c(BLUE_LIGHT), "width": 22, "knock": gap},
    ]


def transform(shapes: list[dict], scale: float, dx: float, dy: float) -> list[dict]:
    out = []
    for shape in shapes:
        new = dict(shape)
        path = []
        for cmd in shape["path"]:
            if cmd[0] == "Z":
                path.append(cmd)
            else:
                coords = [v * scale + (dx if i % 2 == 0 else dy) for i, v in enumerate(cmd[1:])]
                path.append((cmd[0], *coords))
        new["path"] = path
        if "width" in shape:
            new["width"] = shape["width"] * scale
        if "knock" in shape:
            new["knock"] = shape["knock"] * scale
        out.append(new)
    return out


def circle(cx: float, cy: float, r: float) -> list[tuple]:
    k = 0.5522847498 * r
    return [("M", cx + r, cy), ("C", cx + r, cy + k, cx + k, cy + r, cx, cy + r),
            ("C", cx - k, cy + r, cx - r, cy + k, cx - r, cy), ("C", cx - r, cy - k, cx - k, cy - r, cx, cy - r),
            ("C", cx + k, cy - r, cx + r, cy - k, cx + r, cy), ("Z",)]


def rect(x: float, y: float, w: float, h: float) -> list[tuple]:
    return [("M", x, y), ("L", x + w, y), ("L", x + w, y + h), ("L", x, y + h), ("Z",)]


def icon_shapes(small: bool = False) -> list[dict]:
    """The mark on a round dark tile: readable on light and dark panels alike.

    Below 32 px the infinity sign is left out and the lotus and flame are drawn
    larger: at 16 px the full mark is a smudge.
    """
    tile = [{"path": circle(256, 256, 256), "fill": SURFACE}]
    if small:
        return tile + transform(mark_shapes()[:-1], 0.92, 20.5, 63.7)
    return tile + transform(mark_shapes(), 0.80, 51.2, 46)


