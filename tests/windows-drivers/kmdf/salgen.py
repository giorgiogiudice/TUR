"""Empty definitions for the source annotations (SAL) a tree uses.

Microsoft's sources are annotated for the WDK's static analysers
(_IRQL_requires_max_(DISPATCH_LEVEL), __drv_aliasesMem, __in_opt, ...).
They mean nothing to a compiler. mingw-w64's sal.h and driverspecs.h define
some of them; this writes a header that defines every other one the sources
use as nothing, each under #ifndef, so that a definition the system headers
already made is kept. It is force-included after sal.h and driverspecs.h.

Only names shaped like annotations are touched: new-style names that start
with an underscore and a capital letter, end with an underscore and contain a
lower-case letter (architecture and include-guard macros such as _AMD64_ or
_NTDDK_ are all capitals and are never touched), and old-style names from a
fixed list of SAL 1 stems.

  salgen.py OUTPUT_HEADER TREE...
"""

from __future__ import annotations

import os
import re
import sys

NEW = re.compile(r"\b(_[A-Z][A-Za-z0-9_]*_)\b")
OLD_STEMS = (
    "in", "out", "inout", "deref", "field", "range", "checkReturn", "success", "nullterminated",
    "nullnullterminated", "possibly_notnullterminated", "format_string", "reserved", "callback", "typefix",
    "analysis_assume", "notnull", "maybenull", "drv", "control_entrypoint", "post", "pre", "exceptthat",
    "bcount", "ecount", "xcount", "readonly", "struct_bcount", "struct_xcount", "override", "fallthrough",
    "transfer", "data_entrypoint", "kernel_entry", "kernel_driver", "user_driver", "user_code",
    "kernel_code", "in_range", "out_range", "valid", "notvalid", "refparam", "elem_readableTo",
    "elem_writableTo", "byte_readableTo", "byte_writableTo", "allocator", "bound", "file_parser",
    "file_parser_class", "file_parser_library", "source_code_content", "warn_unused_result",
)
OLD = re.compile(r"\b(__(?:" + "|".join(sorted(OLD_STEMS, key=len, reverse=True)) + r")(?:_\w*)?)\b")
STRIP = re.compile(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\\n])*"', re.S)
# Names a stem matches that are not annotations (none known so far; the
# stems need an underscore or the end of the name after them, so __inline,
# __int64 and __inbyte never match).
NEVER: set[str] = set()


def main(argv: list[str]) -> int:
    out, trees = argv[0], argv[1:]
    names: dict[str, bool] = {}  # name -> used with an argument list
    texts = []
    for tree in trees:
        for root, _dirs, files in os.walk(tree):
            if os.sep + "um" in root or "umdf" in root:
                continue
            for name in files:
                if name.lower().endswith((".h", ".hpp", ".c", ".cpp")):
                    with open(os.path.join(root, name), encoding="latin-1") as f:
                        texts.append(STRIP.sub(" ", f.read()))
    # A name the sources define themselves anywhere (often under #ifndef) is
    # left to them.
    defined = {w for text in texts for w in re.findall(r"^\s*#\s*define\s+(\w+)", text, re.M)}
    for text in texts:
        if True:
                for regex in (NEW, OLD):
                    for m in regex.finditer(text):
                        word = m.group(1)
                        if word in defined or word in NEVER:
                            continue
                        if regex is NEW and not any(c.islower() for c in word):
                            continue
                        rest = text[m.end():m.end() + 40].lstrip()
                        names[word] = names.get(word, False) or rest.startswith("(")
    lines = [
        "/* Generated by tests/windows-drivers/kmdf/salgen.py: source annotations",
        "   with no meaning to a compiler, defined as nothing. */",
        "#pragma once",
    ]
    for word in sorted(names):
        lines += [f"#ifndef {word}", f"#define {word}{'(...)' if names[word] else ''}", "#endif"]
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"salgen: {len(names)} annotation names")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
