#!/usr/bin/env bash
# SPDX-License-Identifier: LicenseRef-TUR-Noncommercial-1.0.0
#
# Builds the Kernel-Mode Driver Framework runtime, Wdf01000.sys, from
# Microsoft's MIT-licensed Windows-Driver-Frameworks sources with an open
# toolchain (clang and lld, Fedora's mingw-w64 headers and import
# libraries), and records how far that gets. No WDK, no MSVC, no Microsoft
# binary: the only thing fetched from Microsoft is the source repository, at
# a pinned commit.
#
#   tests/windows-drivers/kmdf/build-wdf.sh OUTPUT_DIR [WINE_SPEC_DIR...]
#
# Inputs, besides the fetched sources:
#   third-party/wdf/patches/*.patch   changes to Microsoft's files (MIT)
#   third-party/wdf/compat/           headers and sources written for this
#                                     build, standing in for the WDK's
#                                     private headers and generated files (MIT)
#   third-party/wdf/sources.txt       the files that make up Wdf01000.sys
#   WINE_SPEC_DIR                     Wine source trees whose ntoskrnl.exe,
#                                     hal and usbd.sys .spec files the import
#                                     list is compared with (imports.py)
#
# Output in OUTPUT_DIR:
#   Wdf01000.sys        when every file compiled and the image linked
#   wdf/summary.txt     per-file result, error counts, the most frequent errors
#   wdf/logs/*.log      compiler output per file
#   wdf/undefined.txt   symbols the objects need from outside (the imports)
#   wdf/imports.md      those imports classified against Wine (imports.py)
#
# Never fails because the framework does not build: the result is the
# summary. Fails only when the sources cannot be fetched or patched.
set -uo pipefail

WDF_REPO=https://github.com/microsoft/Windows-Driver-Frameworks
WDF_COMMIT=b6191d9543441329154da32f7ab9bdd97228dd3c
KMDF_MINOR=33

here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "${here}/../../.." && pwd)"
tp="${repo}/third-party/wdf"
out="$(mkdir -p "${1:?output directory required}" && cd "$1" && pwd)"
shift
wine_trees=("$@")
work="${out}/wdf"
rm -rf "${work}"
mkdir -p "${work}/logs" "${work}/obj" "${work}/gen"
summary="${work}/summary.txt"
: >"${summary}"
note() { echo "$*" | tee -a "${summary}"; }

# ------------------------------------------------------------------ sources
src="${work}/src"
git init -q "${src}" && git -C "${src}" remote add origin "${WDF_REPO}" &&
    git -C "${src}" fetch -q --depth 1 origin "${WDF_COMMIT}" &&
    git -C "${src}" checkout -q FETCH_HEAD || { note "fetch: FAILED"; exit 1; }
note "source: ${WDF_REPO} ${WDF_COMMIT} ($(git -C "${src}" log -1 --format=%cs))"
cmp -s "${src}/LICENSE" "${tp}/LICENSE" && note "licence: MIT, identical to third-party/wdf/LICENSE" ||
    note "licence: DIFFERS from third-party/wdf/LICENSE"

# Windows file names are case-insensitive and #include lines use backslashes;
# normalise the separators (a mechanical change, not a patch), then apply
# the patches.
grep -rlE '^\s*#\s*include\s*[<"][^>"]*\\' "${src}/src" | while read -r f; do
    sed -i -E '/^\s*#\s*include/ s#\\#/#g' "${f}"
done
for p in "${tp}"/patches/*.patch; do
    [ -e "${p}" ] || continue
    if git -C "${src}" apply --whitespace=nowarn "${p}"; then
        note "patch: $(basename "${p}")"
    else
        note "patch: $(basename "${p}") FAILED to apply"
        exit 1
    fi
done

fw="${src}/src/framework"
pub="${src}/src/publicinc/wdf/kmdf/1.${KMDF_MINOR}"
sysroot=/usr/x86_64-w64-mingw32/sys-root/mingw
ddk="${sysroot}/include/ddk"

# The include path of the KMDF build, in order: TUR's stand-ins, the
# framework's own directories (kernel-mode ones only), the public headers,
# then the mingw-w64 SDK and DDK.
incdirs=("${tp}/compat")
while read -r d; do incdirs+=("${d}"); done < <(
    find "${fw}/kmdf" "${fw}/shared" -type d ! -path '*/um' ! -path '*/um/*' | sort)
incdirs+=("${pub}" "${ddk}")
# The mingw-w64 SDK headers come last, as system headers (clang's MinGW
# driver adds them); the include map also resolves names against them.
searchdirs=("${incdirs[@]}" "${sysroot}/include")

# WPP's trace message headers (*.tmh) are generated by a WDK tool; empty
# stand-ins turn WPP off and leave the framework's DbgTrace.h route.
grep -rhoE '#\s*include\s*"[^"]+\.tmh"' "${fw}" | sed -E 's/.*"(.*)"/\1/' | sort -u | while read -r t; do
    : >"${work}/gen/${t}"
done
# Case-insensitive resolution of every #include, as the WDK's compiler sees
# it on Windows: a link per spelling, in the include path's order.
python3 -I "${here}/incmap.py" "${work}/gen" "${fw}" "${pub}" "${tp}/compat" -- "${searchdirs[@]}" >"${work}/incmap.log" 2>&1 ||
    { note "incmap: FAILED"; tail -n 20 "${work}/incmap.log"; exit 1; }
note "include map: $(grep -c '^link' "${work}/incmap.log") case links, $(ls "${work}/gen" | grep -c '\.tmh$') empty .tmh stand-ins"
# SAL annotations the mingw-w64 headers do not define, found in the sources.
python3 -I "${here}/salgen.py" "${work}/gen/tur-sal-generated.h" "${fw}" "${pub}" "${tp}/compat" >>"${work}/incmap.log" 2>&1 ||
    { note "salgen: FAILED"; exit 1; }
note "SAL stand-ins: $(grep -c '^#define' "${work}/gen/tur-sal-generated.h")"

cxx=(clang++ --target=x86_64-w64-mingw32)
cc=(clang --target=x86_64-w64-mingw32)
defs=(-D_AMD64_ -DAMD64 -D_WIN64 -D_KERNEL_MODE -DNTDDI_VERSION=0x0A00000C -D_WIN32_WINNT=0x0A00 -DWINVER=0x0A00
    -DFX_CORE_KERNEL_MODE=0 -DFX_CORE_USER_MODE=1 -DFX_CORE_MODE=0
    -D__WDF_MAJOR_VERSION=1 -D__WDF_MINOR_VERSION=${KMDF_MINOR} -D__WDF_BUILD_NUMBER=0
    -D__WDF_MAJOR_VERSION_STRING=01 -D__WDF_MINOR_VERSION_STRING=0${KMDF_MINOR}
    -DKMDF_VERSION_MAJOR=1 -DKMDF_VERSION_MINOR=${KMDF_MINOR} -DKMDF_MINIMUM_VERSION_REQUIRED=${KMDF_MINOR}
    -DWDF_PRODUCTION_RELEASE=1 -DDBG=0 -DPOOL_NX_OPTIN=1 -DUNICODE -D_UNICODE)
common=(-O1 -g0
    -fms-extensions -fno-builtin-malloc -fno-stack-protector -fno-strict-aliasing -fwrapv -mno-red-zone
    -ferror-limit=0 -w -Wno-error
    -I"${work}/gen" -include "${tp}/compat/tur-wdf-prelude.h")
for d in "${incdirs[@]}"; do common+=(-I"${d}"); done
# -fms-compatibility alone would hide __GNUC__ from mingw-w64's headers,
# which then lose their GNU attribute and intrinsic definitions.
cxxflags=(-std=gnu++14 -nostdinc++ -fms-compatibility -fgnuc-version=4.2.1 -fdelayed-template-parsing -fno-exceptions -fno-rtti
    -fno-threadsafe-statics -fno-sized-deallocation -fno-use-cxa-atexit)

{
    echo "clang: $(clang --version | head -n 1)"
    echo "mingw-w64 headers: $(rpm -q mingw64-headers 2>/dev/null)"
    echo "c++ flags: ${cxx[*]} ${defs[*]} ${cxxflags[*]} ${common[*]}"
} >"${work}/toolchain.txt"
note "toolchain: $(head -n 1 "${work}/toolchain.txt"), $(rpm -q mingw64-headers 2>/dev/null)"

# ------------------------------------------------------------------ compile
mapfile -t files < <(grep -vE '^\s*(#|$)' "${tp}/sources.txt")
compile() { # relative-path
    local rel="$1" srcfile name log
    if [[ "${rel}" == compat/* ]]; then srcfile="${tp}/${rel}"; else srcfile="${fw}/${rel}"; fi
    name="$(echo "${rel}" | tr '/' '_')"
    log="${work}/logs/${name%.*}.log"
    case "${srcfile}" in
    *.c) "${cc[@]}" -std=gnu11 "${defs[@]}" "${common[@]}" -c -o "${work}/obj/${name%.*}.o" "${srcfile}" >"${log}" 2>&1 ;;
    *) "${cxx[@]}" "${defs[@]}" "${cxxflags[@]}" "${common[@]}" -c -o "${work}/obj/${name%.*}.o" "${srcfile}" >"${log}" 2>&1 ;;
    esac
    echo "$? ${rel}"
}
results="${work}/results.txt"
: >"${results}"
jobs="$(nproc)"
for rel in "${files[@]}"; do
    while [ "$(jobs -rp | wc -l)" -ge "${jobs}" ]; do wait -n; done
    compile "${rel}" >>"${results}" &
done
wait
ok=$(awk '$1==0' "${results}" | wc -l)
bad=$(awk '$1!=0' "${results}" | wc -l)
note "compile: ${ok} of ${#files[@]} files ok, ${bad} failed"
total_errors=$(cat "${work}"/logs/*.log | grep -c ' error: ')
note "errors: ${total_errors} in all"
{
    echo
    echo "== failed files (errors each)"
    awk '$1!=0 {print $2}' "${results}" | sort | while read -r rel; do
        name="$(echo "${rel}" | tr '/' '_')"
        printf '%5d  %s\n' "$(grep -c ' error: ' "${work}/logs/${name%.*}.log")" "${rel}"
    done
    echo
    echo "== the most frequent errors (message, with identifiers kept)"
    cat "${work}"/logs/*.log | grep ' error: ' | sed -E 's/^.* error: //' | sort | uniq -c | sort -rn | head -n 150
    echo
    echo "== where they are reported (header files, most first)"
    cat "${work}"/logs/*.log | grep ' error: ' | sed -E 's/:[0-9]+:[0-9]+: error:.*//' | sed "s|${src}/||; s|${tp}/||" |
        sort | uniq -c | sort -rn | head -n 60
    echo
    echo "== fatal errors"
    cat "${work}"/logs/*.log | grep 'fatal error' | sed "s|${src}/||" | sort | uniq -c | sort -rn | head -n 40
} >>"${summary}"

# ------------------------------------------------------------------ imports
llvm-nm --version >/dev/null 2>&1 && nm=llvm-nm || nm=x86_64-w64-mingw32-nm
if ls "${work}"/obj/*.o >/dev/null 2>&1; then
    "${nm}" -g --defined-only "${work}"/obj/*.o 2>/dev/null | awk 'NF==3 {print $3}' | sort -u >"${work}/defined.txt"
    "${nm}" -u "${work}"/obj/*.o 2>/dev/null | awk '{print $NF}' | sed 's/^__imp_//' | sort -u |
        comm -23 - "${work}/defined.txt" >"${work}/undefined.txt"
    note "undefined symbols across the compiled objects: $(wc -l <"${work}/undefined.txt")"
    if [ "${#wine_trees[@]}" -gt 0 ]; then
        python3 -I "${here}/imports.py" --undefined "${work}/undefined.txt" --sources "${fw}" \
            --mingw-lib "${sysroot}/lib" --extra-module WdfRegisterLibrary=wdfldr.sys \
            --extra-module WdfLdrQueryInterface=wdfldr.sys --extra-module WdfVersionBindClass=wdfldr.sys \
            --extra-module WdfRegisterClassLibrary=wdfldr.sys --out "${work}/imports.md" --json "${work}/imports.json" "${wine_trees[@]}" \
            >"${work}/imports.log" 2>&1 || note "imports.py: FAILED (see imports.log)"
        [ -f "${work}/imports.md" ] && head -n 30 "${work}/imports.md" | tee -a "${summary}"
    fi
fi

# ------------------------------------------------------------------ link
if [ "${bad}" -eq 0 ]; then
    bash "${here}/link-wdf.sh" "${work}" "${out}" "${LINK_WINE_TREE:-${wine_trees[0]:-}}" 2>&1 | tee -a "${summary}"
else
    note "link: not attempted (files failed to compile)"
fi
exit 0
