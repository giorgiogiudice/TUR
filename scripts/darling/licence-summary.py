"""The licence files of Darling and every submodule, in a form a person can review.

Run by build-darling.sh inside the build, on the checkout at the pinned
commit, before anything is compiled. Writes:

  licences.md    one row per repository (Darling and each submodule): its
                 commit, the licence files at its top level, the licences
                 their text looks like, and a mark when none was found; then
                 the text of every distinct licence file once (identical
                 files are named, not repeated)
  licences.json  the same, for tools

The detection is a reading aid, keyed on phrases every copy of a licence
contains; it decides nothing. The first publish of TUR's Darling is blocked
until a person has read these files and summarised them in
docs/reports/macos-darling-1.md (owner's decision, 16 November 2026).
"""

import argparse
import hashlib
import json
import os
import re
import sys

NAMES = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|APPLE_LICENSE|NOTICE|UNLICENSE|APSL)", re.I)
MARKERS = [
    ("GPL-3.0", r"GNU GENERAL PUBLIC LICENSE\s+Version 3"),
    ("GPL-2.0", r"GNU GENERAL PUBLIC LICENSE\s+Version 2"),
    ("LGPL-2.1", r"GNU LESSER GENERAL PUBLIC LICENSE\s+Version 2\.1"),
    ("LGPL-3.0", r"GNU LESSER GENERAL PUBLIC LICENSE\s+Version 3"),
    ("LGPL-2.0", r"GNU LIBRARY GENERAL PUBLIC LICENSE"),
    ("AGPL-3.0", r"GNU AFFERO GENERAL PUBLIC LICENSE"),
    ("APSL-2.0", r"APPLE PUBLIC SOURCE LICENSE\s+Version 2\.0"),
    ("APSL-1.x", r"APPLE PUBLIC SOURCE LICENSE\s+Version 1\."),
    ("Apache-2.0", r"Apache License,?\s+Version 2\.0"),
    ("MPL-2.0", r"Mozilla Public License,?\s+(Version|v\.)\s*2\.0"),
    ("MIT", r"Permission is hereby granted, free of charge, to any person obtaining"),
    ("BSD-3-Clause", r"Neither the name of .{0,200}? nor the names of"),
    ("BSD-2-Clause", r"Redistributions in binary form must reproduce the above copyright"),
    ("ISC", r"Permission to use, copy, modify, and(/or)? distribute this software for any"),
    ("Zlib", r"This software is provided 'as-is', without any express or implied"),
    ("PSF", r"PYTHON SOFTWARE FOUNDATION LICENSE"),
    ("Artistic", r"The Artistic License"),
    ("Unicode", r"UNICODE, INC\. LICENSE AGREEMENT"),
    ("Public domain", r"public domain"),
]


def detect(text):
    found = []
    for name, pattern in MARKERS:
        if re.search(pattern, text, re.I | re.S):
            found.append(name)
    # BSD-3 text also matches the BSD-2 marker.
    if "BSD-3-Clause" in found and "BSD-2-Clause" in found:
        found.remove("BSD-2-Clause")
    return found or ["unrecognised"]


def repositories(source, submodules_file):
    rows = [(".", "", "darling")]
    for line in open(submodules_file):
        parts = line.strip().lstrip("+-U").split()
        if len(parts) >= 2:
            rows.append((parts[1], parts[0], parts[1]))
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", required=True)
    parser.add_argument("--submodules", required=True, help="git submodule status --recursive output")
    parser.add_argument("--markdown", required=True)
    parser.add_argument("--json", required=True)
    args = parser.parse_args()

    texts = {}
    entries = []
    for path, commit, name in repositories(args.source, args.submodules):
        directory = os.path.join(args.source, path)
        files = []
        if os.path.isdir(directory):
            for item in sorted(os.listdir(directory)):
                full = os.path.join(directory, item)
                if NAMES.match(item) and os.path.isfile(full) and not os.path.islink(full):
                    data = open(full, "rb").read()
                    digest = hashlib.sha256(data).hexdigest()
                    text = data.decode("utf-8", "replace")
                    texts.setdefault(digest, {"first": f"{name}/{item}", "text": text, "also": []})
                    if texts[digest]["first"] != f"{name}/{item}":
                        texts[digest]["also"].append(f"{name}/{item}")
                    files.append({"file": item, "sha256": digest, "looks_like": detect(text)})
        looks = sorted({kind for f in files for kind in f["looks_like"]})
        entries.append({"path": path, "commit": commit, "files": files,
                        "looks_like": looks or ["NO LICENCE FILE"]})

    with open(args.json, "w") as handle:
        json.dump({"repositories": entries}, handle, indent=1)

    lines = [
        "# Darling's licence files, for review",
        "",
        "Generated by scripts/darling/licence-summary.py from the pinned checkout. "
        "\"Looks like\" is a reading aid, not a finding. Repositories marked "
        "**NO LICENCE FILE** need their source headers read.",
        "",
        f"{len(entries)} repositories; {sum(1 for e in entries if not e['files'])} without a licence file; "
        f"{len(texts)} distinct licence texts.",
        "",
        "| Repository | Commit | Licence files | Looks like |",
        "|---|---|---|---|",
    ]
    for entry in entries:
        files = ", ".join(f["file"] for f in entry["files"]) or "**NO LICENCE FILE**"
        lines.append(f"| `{entry['path']}` | `{entry['commit'][:12]}` | {files} | {', '.join(entry['looks_like'])} |")
    lines += ["", "## The texts", ""]
    for digest, item in sorted(texts.items(), key=lambda pair: pair[1]["first"]):
        lines.append(f"### {item['first']}")
        if item["also"]:
            lines.append("")
            lines.append("Identical in: " + ", ".join(item["also"]))
        lines += ["", f"SHA-256 `{digest}`", "", "```text", item["text"].rstrip(), "```", ""]
    with open(args.markdown, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"{len(entries)} repositories, {len(texts)} distinct licence texts, "
          f"{sum(1 for e in entries if not e['files'])} without a licence file")
    return 0


if __name__ == "__main__":
    sys.exit(main())
